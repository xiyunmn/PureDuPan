    companion object {
        fun savedValue(key: String, contains: (String) -> Boolean, read: (String) -> Boolean): Boolean {
            if (key == COUPON_GIFT_V3.key && !contains(key)) {
                return read(FeatureKeys.KEY_BLOCK_IN_APP_DIALOG)
            }
            return read(key)
        }
    }
}
