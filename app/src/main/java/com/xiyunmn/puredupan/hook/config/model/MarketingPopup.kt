    OPERATION_IMAGE(FeatureKeys.KEY_BLOCK_IN_APP_DIALOG),
    OPERATION_ANIMATION(FeatureKeys.KEY_BLOCK_POPUP_OPERATION_ANIMATION),
    OPERATION_AFX(FeatureKeys.KEY_BLOCK_POPUP_OPERATION_AFX),
    NEW_USER_OFFER(FeatureKeys.KEY_BLOCK_POPUP_NEW_USER_OFFER),
    NEW_USER_REWARD(FeatureKeys.KEY_BLOCK_POPUP_NEW_USER_REWARD),
    NEW_USER_REWARD_V2(FeatureKeys.KEY_BLOCK_POPUP_NEW_USER_REWARD_V2),
    COIN_PROMOTION(FeatureKeys.KEY_BLOCK_POPUP_COIN_PROMOTION),
    COUPON_GIFT_V3(FeatureKeys.KEY_BLOCK_POPUP_COUPON_GIFT_V3),
