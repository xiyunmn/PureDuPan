    LIFE_V10(FeatureKeys.KEY_BLOCK_POPUP_LIFE_V10),
    LIFE_V10_REPURCHASE(FeatureKeys.KEY_BLOCK_POPUP_LIFE_V10_REPURCHASE),
    LIFE_COMBO(FeatureKeys.KEY_BLOCK_POPUP_LIFE_COMBO),
    LIFE_LIMITED(FeatureKeys.KEY_BLOCK_POPUP_LIFE_LIMITED),
